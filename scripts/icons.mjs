#!/usr/bin/env node
/**
 * Material Symbols Rounded → src/design-system/icons/material-symbols.js
 *
 *   node scripts/icons.mjs          regenerate the glyph module
 *   node scripts/icons.mjs --check  fail if the module is stale or a symbol name is invalid
 *
 * Source: Google's official Material Symbols (Apache-2.0), via the version-pinned
 * @material-symbols/svg-500 package (weight 500, optical size 24, Rounded). Only the symbols Numaya
 * uses are extracted, each in its filled (FILL 1) and unfilled (FILL 0) drawing, so production ships
 * no icon font and no remote request. The semantic name → official symbol name map below is the
 * single place to add an icon.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");
const SRC = resolve(ROOT, "node_modules/@material-symbols/svg-500/rounded");
const OUT = resolve(ROOT, "src/design-system/icons/material-symbols.js");
const VERSION = JSON.parse(readFileSync(resolve(ROOT, "node_modules/@material-symbols/svg-500/package.json"), "utf8")).version;

/** Numaya semantic name → official Material Symbols name. */
export const SYMBOLS = {
  chevronLeft: "chevron_left",
  chevronRight: "chevron_right",
  chevronDown: "keyboard_arrow_down",
  chevronUp: "keyboard_arrow_up",
  arrowRight: "arrow_forward",
  arrowUp: "arrow_upward",
  check: "check",
  plus: "add",
  minus: "remove",
  close: "close",
  search: "search",
  lock: "lock",
  heart: "favorite",
  star: "star",
  delete: "backspace",
  message: "chat_bubble",
  shield: "verified_user",
  verified: "verified",
  flag: "flag",
  block: "block",
  info: "info",
  alert: "warning",
  wifiOff: "wifi_off",
  camera: "photo_camera",
  image: "image",
  mic: "mic",
  send: "arrow_upward",
  more: "more_horiz",
  filter: "tune",
  settings: "settings",
  user: "person",
  userMinus: "person_remove",
  trash: "delete",
  location: "location_on",
  bell: "notifications",
  eyeOff: "visibility_off",
  undo: "undo",
  interests: "interests",
  sparkle: "star_shine",
  cards: "cards_stack",
};

const pathOf = (file) => {
  const svg = readFileSync(resolve(SRC, file), "utf8");
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
  if (!paths.length) throw new Error(`No path in ${file}`);
  return paths.join(" ");
};

const lines = [
  "// Generated by scripts/icons.mjs from Material Symbols Rounded (Google, Apache-2.0),",
  `// @material-symbols/svg-500 ${VERSION}: weight 500, optical size 24. Do not edit; run \`npm run icons\`.`,
  "// Each entry: [FILL 1 path, FILL 0 path] on the 0 -960 960 960 grid.",
  `export const MATERIAL_SYMBOLS_VERSION = "${VERSION}";`,
  "export const SYMBOL_NAMES = {",
  ...Object.entries(SYMBOLS).map(([k, v]) => `  ${k}: "${v}",`),
  "};",
  "export const GLYPHS = {",
  ...Object.entries(SYMBOLS).map(([k, v]) => `  ${k}: [${JSON.stringify(pathOf(`${v}-fill.svg`))}, ${JSON.stringify(pathOf(`${v}.svg`))}],`),
  "};",
  "",
];
const out = lines.join("\n");

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {}
  if (current !== out) {
    console.error("Icon module is stale. Run `npm run icons`.");
    process.exit(1);
  }
  console.log(`Icons OK: ${Object.keys(SYMBOLS).length} Material Symbols Rounded glyphs, generated module up to date.`);
} else {
  writeFileSync(OUT, out);
  console.log(`Wrote ${Object.keys(SYMBOLS).length} glyphs → src/design-system/icons/material-symbols.js`);
}
